'use client';

/**
 * Admin panel TR/EN. The locale is resolved once at module load so `t()` works
 * anywhere — including module-scope arrays such as the sidebar definition.
 * Switching persists the choice and reloads the panel, which is a perfectly
 * acceptable trade-off for an internal staff tool and keeps this file tiny.
 */
export type Locale = 'tr' | 'en';

const STORAGE_KEY = 'pulse.admin.locale';

const detect = (): Locale => {
  if (typeof window === 'undefined') return 'tr';
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'tr' || stored === 'en') return stored;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
};

export const locale: Locale = detect();

export const setLocale = (next: Locale) => {
  if (next === locale) return;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  window.location.reload();
};

